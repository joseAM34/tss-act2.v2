CREATE TABLE wrangling_run (
    id VARCHAR(36) PRIMARY KEY,
    requested_origin VARCHAR(24) NOT NULL CHECK (requested_origin IN ('REAL', 'SINTETICO', 'NO_DECLARADO')),
    publication_mode VARCHAR(16) NOT NULL CHECK (publication_mode IN ('BORRADOR', 'OFICIAL')),
    cutoff_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor VARCHAR(100) NOT NULL,
    input_count INTEGER NOT NULL CHECK (input_count >= 0),
    included_count INTEGER NOT NULL CHECK (included_count >= 0),
    logical_hash VARCHAR(64) NOT NULL,
    bundle_hash VARCHAR(64) NOT NULL,
    bundle_json TEXT NOT NULL
);

CREATE TABLE wrangling_member (
    run_id VARCHAR(36) NOT NULL REFERENCES wrangling_run(id) ON DELETE CASCADE,
    response_id VARCHAR(36) NOT NULL,
    capture_hash VARCHAR(64) NOT NULL,
    included BOOLEAN NOT NULL,
    exclusion_reason VARCHAR(100) NOT NULL,
    revisions_json TEXT NOT NULL,
    PRIMARY KEY (run_id, response_id)
);

CREATE TABLE wrangling_correction (
    id VARCHAR(36) PRIMARY KEY,
    revision_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    response_id VARCHAR(36) NOT NULL REFERENCES survey_response(id) ON DELETE CASCADE,
    question_id VARCHAR(64) NOT NULL,
    values_json TEXT NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    actor VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_wrangling_correction_response ON wrangling_correction(response_id, created_at);

CREATE TABLE wrangling_origin_classification (
    id VARCHAR(36) PRIMARY KEY,
    revision_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    response_id VARCHAR(36) NOT NULL REFERENCES survey_response(id) ON DELETE CASCADE,
    origin VARCHAR(24) NOT NULL CHECK (origin IN ('REAL', 'SINTETICO', 'NO_DECLARADO')),
    reason VARCHAR(1000) NOT NULL,
    actor VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_wrangling_origin_response ON wrangling_origin_classification(response_id, created_at);

CREATE TABLE wrangling_text_coding (
    id VARCHAR(36) PRIMARY KEY,
    revision_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    response_id VARCHAR(36) NOT NULL REFERENCES survey_response(id) ON DELETE CASCADE,
    question_id VARCHAR(64) NOT NULL,
    themes_json TEXT NOT NULL,
    source_value_hash VARCHAR(64) NOT NULL,
    codebook_version VARCHAR(100) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    actor VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_wrangling_coding_response ON wrangling_text_coding(response_id, created_at);
